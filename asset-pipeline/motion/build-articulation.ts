import { format, resolveConfig } from 'prettier'
/** Derive distal pivots from registered BodyParts3D surfaces. The atlas and the performer use identical bind coordinates. */
import { writeFile } from 'node:fs/promises'
import { NodeIO } from '@gltf-transform/core'
import { KHRDracoMeshCompression } from '@gltf-transform/extensions'
import draco from 'draco3dgltf'
import { Vector3 } from 'three'
import { structureByMesh } from '../../src/anatomy/catalogue'
const io = new NodeIO()
  .registerExtensions([KHRDracoMeshCompression])
  .registerDependencies({ 'draco3d.decoder': await draco.createDecoderModule() })
const nodes = (await io.read('public/models/male-skeleton.glb')).getRoot().listNodes()
const bones = new Map<string, { id: string; points: Vector3[]; center: Vector3 }>()
for (const n of nodes) {
  const s = structureByMesh.get(n.getName()),
    pos = n.getMesh()?.listPrimitives()[0].getAttribute('POSITION')
  if (!s || !pos) continue
  if (!['Hands', 'Feet', 'Teeth', 'Skull and hyoid'].includes(s.region)) continue
  const points = Array.from({ length: pos.getCount() }, (_, i) =>
    new Vector3().fromArray(pos.getElement(i, [])),
  )
  const center = points.reduce((v, q) => v.add(q), new Vector3()).divideScalar(points.length)
  bones.set(s.displayName.toLowerCase(), { id: s.meshName, points, center })
}
const array = (v: Vector3) => v.toArray().map((x) => Number(x.toFixed(6)))
const joints: [string, number, number[]][] = [],
  bindings: Record<string, number> = {},
  tips: Record<string, number[]> = {}
const insert = (name: string, parent: number, p: Vector3) => {
  joints.push([name, parent, array(p)])
  return 19 + joints.length
}
const at = (name: string) => {
  const b = bones.get(name)
  if (!b) throw Error('No registered surface for ' + name)
  return b
}
const jaw = at('mandible'),
  condyles = jaw.points
    .filter((v) => Math.abs(v.x - jaw.center.x) > 0.043)
    .sort((a, b) => b.y - a.y)
    .slice(0, Math.ceil(jaw.points.length * 0.01))
const hinge = condyles.reduce((a, b) => a.add(b), new Vector3()).divideScalar(condyles.length)
hinge.x = jaw.center.x
const jawIndex = insert('jaw', 5, hinge)
bindings[jaw.id] = jawIndex
for (const [name, b] of bones)
  if (name.includes('lower ') && name.includes('tooth')) bindings[b.id] = jawIndex
function endBand(points: Vector3[], axis: Vector3, far = false) {
  const sorted = [...points].sort((a, b) => (a.dot(axis) - b.dot(axis)) * (far ? -1 : 1))
  const band = sorted.slice(0, Math.max(3, Math.ceil(sorted.length * 0.12)))
  return band.reduce((a, b) => a.add(b), new Vector3()).divideScalar(band.length)
}
const fingers = [
  ['Thumb', 'thumb'],
  ['Index', 'index finger'],
  ['Middle', 'middle finger'],
  ['Ring', 'ring finger'],
  ['Little', 'little finger'],
] as const
const toes = [
  ['ToeBig', 'big toe'],
  ['ToeTwo', 'second toe'],
  ['ToeThree', 'third toe'],
  ['ToeFour', 'fourth toe'],
  ['ToeLittle', 'little toe'],
] as const
for (const side of ['left', 'right'])
  for (const [digit, display] of [...fingers, ...toes]) {
    const foot = digit.startsWith('Toe'),
      thumb = digit === 'Thumb'
    const chain = (
      thumb || digit === 'ToeBig' ? ['Proximal', 'Distal'] : ['Proximal', 'Middle', 'Distal']
    ).map((p) => at(p.toLowerCase() + ' phalanx of ' + side + ' ' + display))
    let parent = foot ? (side === 'left' ? 14 : 17) : side === 'left' ? 8 : 11
    if (thumb) {
      const met = at(side + ' first metacarpal bone'),
        axis = chain[0].center.clone().sub(met.center).normalize()
      parent = insert(side + digit + '0', parent, endBand(met.points, axis))
      bindings[met.id] = parent
    }
    for (const [i, bone] of chain.entries()) {
      const axis = (
        i < chain.length - 1
          ? chain[i + 1].center.clone().sub(bone.center)
          : bone.center.clone().sub(chain[i - 1].center)
      ).normalize()
      const name = side + digit + (i + 1)
      parent = insert(name, parent, endBand(bone.points, axis))
      bindings[bone.id] = parent
      if (i === chain.length - 1) tips[side + digit] = array(endBand(bone.points, axis, true))
    }
  }
const output = 'src/motion/distalJoints.ts'
await writeFile(
  output,
  await format(
    '// Generated by build:articulation from the registered skeleton GLB. Coordinates are metres.\nexport const distalJoints = ' +
      JSON.stringify(joints) +
      ' as const\nexport const distalBindings: Record<string,number> = ' +
      JSON.stringify(bindings) +
      '\nexport const digitTips = ' +
      JSON.stringify(tips) +
      ' as const\n',
    { ...(await resolveConfig(output)), filepath: output },
  ),
)
console.log(
  joints.length + ' distal joints, ' + Object.keys(bindings).length + ' source bones bound.',
)
